namespace ArxisStudio.Surface.UiDesigner;

/// <summary>
/// Определяет, как редактор находит редактируемые элементы внутри контейнера.
/// </summary>
public enum SurfaceContentMode
{
    /// <summary>
    /// Содержимое размечено вручную: target'ом становится только контрол
    /// с designer-метаданными — <c>Layout.IsTracked</c> либо <c>Layout.X</c>/<c>Y</c>.
    /// </summary>
    /// <remarks>
    /// Подходит для шаблонов, написанных вместе с приложением: автор сам решает,
    /// что редактируется, а что остаётся оформлением.
    /// </remarks>
    Annotated,

    /// <summary>
    /// Содержимое пришло целиком — например, форма, загруженная из <c>.axaml</c>.
    /// Редактируется любой элемент разметки, а сама форма не реагирует на ввод.
    /// </summary>
    /// <remarks>
    /// Размечать загруженную форму некому, поэтому target'ом может стать любой
    /// её элемент. Внутренности контролов при этом не выбираются: у частей
    /// шаблона задан <c>TemplatedParent</c>, у написанного в разметке — нет.
    /// <para>
    /// Ввод гасится, иначе форма жила бы своей жизнью: кнопка съедала бы нажатие,
    /// а текстовое поле забирало фокус и принимало текст. Выделение от этого
    /// не страдает — оно считается по прямоугольникам, а не через hit-testing.
    /// </para>
    /// </remarks>
    Loaded
}
