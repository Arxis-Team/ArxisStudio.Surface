using System;
using Avalonia.Controls;

namespace ArxisStudio.Surface.UiDesigner;

/// <summary>
/// Хранилище принадлежности контролов design-time группам.
/// </summary>
/// <remarks>
/// Редактор владеет <b>смыслом</b> группы — путём, кластерами, входом внутрь, отменой, — но не
/// местом, где лежит пометка. Место принадлежит владельцу документа, и причина измеримая: из
/// четырёх значений, которые редактор пишет в чужие контролы, у трёх есть читатель в рантайме
/// (<c>Layout.X</c>/<c>Y</c> читает <c>AbsolutePanel</c>, <c>Width</c>/<c>Height</c> и
/// <c>ZIndex</c> — сама Avalonia), а у группы читателя нет ни одного. Записанная в разметку, она
/// означала бы, что выпущенное приложение тащит сборку редактора, чтобы разобрать собственное
/// окно, а грамматика пути становится частью формата документа. См. ADR 0002.
/// <para>
/// Умолчание — <see cref="DesignGroupAttachedStore"/>: пометка живёт в attached-свойстве
/// <see cref="DesignGroup"/> на самом контроле и сохраняется тем же способом, что и
/// <c>Layout.X</c>/<c>Y</c>. Своё хранилище задаёт тот, кому эта цена не подходит.
/// </para>
/// <para>
/// Ключ здесь — сам контрол, и живёт он ровно столько, сколько живёт загруженная форма.
/// Хранилищу, которое переживает перезагрузку разметки, нужен ключ документа — в
/// <c>ArxisStudio.Markup</c> это узел и путь к нему, — а перевод «контрол ↔ узел» делает хост:
/// редактор о документе не знает ничего и знать не должен.
/// </para>
/// </remarks>
public interface IDesignGroupStore
{
    /// <summary>
    /// Возвращает путь группы контрола.
    /// </summary>
    /// <param name="target">Контрол.</param>
    /// <returns>Путь группы или <see langword="null"/>, если контрол не сгруппирован.</returns>
    /// <remarks>
    /// Спрашивается часто — на каждом кадре жеста и на каждой пересборке оверлея, — поэтому
    /// ответ обязан быть дешёвым. Обход документа на каждый вызов сделал бы жест зависимым от
    /// размера макета: ровно эту зависимость редактор у себя уже однажды убирал снимком.
    /// </remarks>
    string? GetGroup(Control target);

    /// <summary>
    /// Задает путь группы контрола.
    /// </summary>
    /// <param name="target">Контрол.</param>
    /// <param name="path">Путь группы или <see langword="null"/>, если контрол больше не сгруппирован.</param>
    /// <remarks>
    /// Вызывается только швом редактора, то есть внутри единицы редактирования: отмена и повтор
    /// проходят этим же путём и пишут в то же хранилище.
    /// </remarks>
    void SetGroup(Control target, string? path);

    /// <summary>
    /// Происходит, когда состав групп изменился помимо редактора.
    /// </summary>
    /// <remarks>
    /// О своих правках редактор знает сам — событие про чужие: правку в документе, отмену на
    /// стороне хоста, перезагрузку формы. Получив его, редактор пересобирает оверлей: кластеры
    /// считаются по пометке, и рамка обязана описывать то, что хранилище говорит сейчас.
    /// <para>
    /// Поднимать нужно в UI-потоке: обработчик трогает визуальное дерево.
    /// </para>
    /// </remarks>
    event EventHandler? GroupsChanged;
}
