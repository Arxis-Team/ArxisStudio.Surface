using Avalonia.Media;

namespace ArxisStudio.Surface.Nodes;

/// <summary>
/// Маркер на проводе: стрелка или другая фигура, показывающая направление потока (ADR 0014).
/// </summary>
/// <remarks>
/// Задаётся редактору целиком (<see cref="NodeEditor.LinkMarker"/>) или каждой связи привязкой
/// (<see cref="NodeEditor.LinkMarkerBinding"/>): у провода исполнения — стрелки, у провода данных —
/// ничего. Объект читается при рисовании, поэтому правку видно после замены объекта целиком или после
/// любой перерисовки; выключает маркеры, не теряя настройки, <see cref="NodeEditor.AreLinkMarkersVisible"/>.
/// Размер и шаг — в мировых единицах: маркер растёт с масштабом, как сам провод, а мельче
/// <see cref="MinScreenSize"/> пикселей экрана не рисуется.
/// </remarks>
public sealed class LinkMarker
{
    /// <summary>
    /// Получает или задает фигуру маркера. По умолчанию — стрелка.
    /// </summary>
    public LinkShape Shape { get; set; } = LinkShape.Arrow;

    /// <summary>
    /// Получает или задает свою фигуру для <see cref="LinkShape.Custom"/>: геометрию в квадрате от −1 до 1,
    /// остриём по оси X. Масштаб — <see cref="Size"/>.
    /// </summary>
    public Geometry? Geometry { get; set; }

    /// <summary>
    /// Получает или задает размер маркера в мировых единицах — длину фигуры по проводу. По умолчанию 14:
    /// мельче стрелка на обычном отдалении графа, около половины масштаба, тонет в самом проводе.
    /// </summary>
    public double Size { get; set; } = 14;

    /// <summary>
    /// Получает или задает шаг между маркерами по длине провода в мировых единицах. Ноль — один маркер
    /// в точке <see cref="Position"/>. По умолчанию ноль.
    /// </summary>
    public double Spacing { get; set; }

    /// <summary>
    /// Получает или задает место одиночного маркера — долю длины провода от выхода: 0 — у выхода,
    /// 1 — у входа. По умолчанию середина.
    /// </summary>
    public double Position { get; set; } = 0.5;

    /// <summary>
    /// Получает или задает кисть маркера. Без неё маркер берёт цвет провода — модели или темы, у
    /// выбранного — цвет выбора.
    /// </summary>
    public IBrush? Brush { get; set; }

    /// <summary>
    /// Получает или задает наименьший размер маркера на экране в пикселях: мельче он не рисуется —
    /// при сильном отдалении стрелки сливались бы в шум. По умолчанию 4.
    /// </summary>
    public double MinScreenSize { get; set; } = 4;
}
