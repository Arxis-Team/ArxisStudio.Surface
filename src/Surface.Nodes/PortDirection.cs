namespace ArxisStudio.Surface.Nodes;

/// <summary>
/// Направление порта: в него входит связь или из него выходит.
/// </summary>
/// <remarks>
/// Связь всегда идёт из выхода во вход. Это единственное правило соединения, которое редактор
/// проверяет сам: без него нечего было бы назвать источником, а остальные правила графа — один
/// вход на порт, без петель, совместимость типов — принадлежат приложению.
/// </remarks>
public enum PortDirection
{
    /// <summary>
    /// Вход: сюда приходит связь, это её цель.
    /// </summary>
    Input,

    /// <summary>
    /// Выход: отсюда выходит связь, это её источник.
    /// </summary>
    Output
}
